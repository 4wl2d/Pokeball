#!/usr/bin/env python3
"""Renders benchmark/results/RESULTS.md from the runner's results.json.

Adds source-level metrics: SLOC (non-blank, non-comment lines), and McCabe
cyclomatic complexity per function from lizard (https://github.com/terryyin/lizard).

Usage: python3 benchmark/report.py results.json benchmark/results
"""
from __future__ import annotations

import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def sources(arch: dict) -> list[Path]:
    base = ROOT / arch["key"] / "src" / "main" / "kotlin"
    toolkit = [base / Path(*p.split(".")) for p in arch["toolkit"]]
    return sorted(f for f in base.rglob("*.kt") if not any(t in f.parents for t in toolkit))


def sloc(files: list[Path]) -> int:
    count = 0
    for f in files:
        text = re.sub(r"/\*.*?\*/", "", f.read_text(encoding="utf-8"), flags=re.S)
        count += sum(1 for line in text.splitlines() if line.strip() and not line.strip().startswith("//"))
    return count


def occurrences(files: list[Path], pattern: str) -> int:
    rx = re.compile(pattern)
    return sum(len(rx.findall(f.read_text(encoding="utf-8"))) for f in files)


def lizard(files: list[Path]) -> dict:
    out = subprocess.run(["lizard", "--csv", *map(str, files)], capture_output=True, text=True, check=True).stdout
    ccn = [int(row.split(",")[1]) for row in out.splitlines() if row.strip()]
    return {"functions": len(ccn), "ccn_mean": sum(ccn) / len(ccn), "ccn_max": max(ccn), "ccn_total": sum(ccn)}


def pct(rate: dict) -> str:
    return f"{100 * rate['rate']:.1f} [{100 * rate['low']:.1f}, {100 * rate['high']:.1f}]"


def main() -> None:
    results = Path(sys.argv[1])
    out = Path(sys.argv[2])
    out.mkdir(parents=True, exist_ok=True)
    data = json.loads(results.read_text())
    if results.resolve() != (out / "results.json").resolve():
        shutil.copy(results, out / "results.json")
    archs = data["architectures"]
    label = {a["key"]: a["label"] for a in archs}
    cells = {(c["architecture"], c["profile"], c["crashes"]): c for c in data["dynamic"]}
    runs = data["config"]["runsPerCell"]
    src = {}
    for a in archs:
        files = sources(a)
        src[a["key"]] = {
            "files": len(files),
            "sloc": sloc(files),
            "catch": occurrences(files, r"\bcatch\s*\("),
            "timeouts": occurrences(files, r"\bwithTimeout\b|timeoutMillis\s*[,)=]"),
            **lizard(files),
        }
        if a["toolkit"]:
            kit = sorted(f for p in a["toolkit"] for f in (ROOT / a["key"] / "src/main/kotlin" / Path(*p.split("."))).rglob("*.kt"))
            src[a["key"]]["toolkit_sloc"] = sloc(kit)

    L = []
    L.append("# Architecture benchmark: results\n")
    L.append(f"Generated by `benchmark/report.py` from `results.json` ({runs} runs per cell). "
             "Method, definitions and threats to validity: [README](../README.md). "
             "Rates are shares of runs, with Wilson 95% intervals in brackets.\n")

    L.append("## 1. Correctness under faults: runs with at least one violated requirement (%)\n")
    cols = [("Stress", False), ("Stress", True), ("Mild", False), ("Mild", True)]
    L.append("| Architecture | " + " | ".join(f"{p}, {'one crash' if c else 'no crash'}" for p, c in cols) + " |")
    L.append("|---|" + "---|" * len(cols))
    for a in archs:
        L.append(f"| {label[a['key']]} | " + " | ".join(pct(cells[(a['key'], p, c)]["anyViolation"]) for p, c in cols) + " |")

    L.append("\n## 2. Which requirement was violated (runs, of " + str(runs) + ", Stress and Mild with one crash)\n")
    kinds = list(data["dynamic"][0]["violations"].keys())
    L.append("| Architecture | Profile | " + " | ".join(kinds) + " |")
    L.append("|---|---|" + "---|" * len(kinds))
    for a in archs:
        for p in ("Stress", "Mild"):
            c = cells[(a["key"], p, True)]
            L.append(f"| {label[a['key']]} | {p} | " + " | ".join(str(c["violations"][k]["hits"]) or "0" for k in kinds) + " |")

    L.append("\n### Seeded bugs (one crash per run)\n")
    L.append("Each correct implementation with one plausible mistake injected from outside its code. "
             "A detected bug shows that a zero rate above is not a blind spot of the oracles.\n")
    L.append("| Seeded bug | Profile | Runs with a violation (%) | Violations seen |")
    L.append("|---|---|---|---|")
    for c in data["seeded"]:
        seen = ", ".join(k for k, v in c["violations"].items() if v["hits"])
        L.append(f"| {c['name']} | {c['profile']} | {pct(c['anyViolation'])} | {seen or '—'} |")

    L.append("\n## 3. What honesty costs (one crash per run)\n")
    L.append("| Architecture | Profile | Orders accepted / run | Completed / accepted order | Needs attention / order | Charge requests / order | Status queries / order |")
    L.append("|---|---|---|---|---|---|---|")
    for a in archs:
        for p in ("Stress", "Mild"):
            c = cells[(a["key"], p, True)]
            done = c["completedPerRun"] / c["acceptedPerRun"] if c["acceptedPerRun"] else 0
            L.append(f"| {label[a['key']]} | {p} | {c['acceptedPerRun']:.2f} | {done:.2f} | {c['needsAttentionPerOrder']:.3f} | "
                     f"{c['chargeRequestsPerOrder']:.2f} | {c['statusRequestsPerOrder']:.2f} |")

    L.append("\n## 4. Structure of the feature code\n")
    L.append("Feature code excludes the shared simulated environment and the `kit` packages that stand in for an actor, MVU or messaging framework "
             "(their size is listed separately). Ballarch's runtime is a library and is likewise excluded; its kernel and runtime types count as framework types.\n")
    st = data["structure"]
    rows = [
        ("Source lines (SLOC)", lambda k: str(src[k]["sloc"])),
        ("Toolkit SLOC excluded", lambda k: str(src[k].get("toolkit_sloc", "—"))),
        ("Bytecode instructions", lambda k: str(st[k]["instructions"])),
        ("Units (named classes)", lambda k: str(st[k]["units"])),
        ("Packages", lambda k: str(st[k]["packages"])),
        ("CBO, mean (max)", lambda k: f"{st[k]['cboMean']:.2f} ({st[k]['cboMax']})"),
        ("LCOM4, mean (share = 1)", lambda k: f"{st[k]['lcom4Mean']:.2f} ({100 * st[k]['lcom4Cohesive']:.0f}%)"),
        ("CAMC, mean", lambda k: f"{st[k]['camcMean']:.2f}"),
        ("Distance from main sequence D, mean", lambda k: "n/a" if st[k]["distanceMean"] is None else f"{st[k]['distanceMean']:.2f}"),
        ("Propagation cost", lambda k: f"{100 * st[k]['propagationCost']:.1f}%"),
        ("Dependency cycles (units in cycles)", lambda k: f"{st[k]['cyclicGroups']} ({st[k]['unitsInCycles']})"),
        ("McCabe CCN per function, mean (max)", lambda k: f"{src[k]['ccn_mean']:.2f} ({src[k]['ccn_max']})"),
        ("McCabe CCN, total", lambda k: str(src[k]["ccn_total"])),
        ("Framework types used", lambda k: str(st[k]["frameworkTypes"])),
        ("`catch` clauses", lambda k: str(src[k]["catch"])),
        ("Share of code in pure units", lambda k: f"{100 * st[k]['pureShare']:.0f}%"),
    ]
    L.append("| Metric | " + " | ".join(label[a["key"]] for a in archs) + " |")
    L.append("|---|" + "---|" * len(archs))
    for name, f in rows:
        L.append(f"| {name} | " + " | ".join(f(a["key"]) for a in archs) + " |")

    L.append("\n## 5. Package metrics (Martin)\n")
    L.append("| Architecture | Package | Ca | Ce | A | I | D |")
    L.append("|---|---|---|---|---|---|---|")
    for a in archs:
        for p in st[a["key"]]["packagesDetail"]:
            L.append(f"| {label[a['key']]} | `{p['name']}` | {p['ca']} | {p['ce']} | {p['A']:.2f} | {p['I']:.2f} | {p['D']:.2f} |")

    version = subprocess.run(["lizard", "--version"], capture_output=True, text=True).stdout.strip()
    L.append(f"\nSource metrics: lizard {version}. Structural metrics: `benchmark/runner` (ASM bytecode analysis).\n")
    L.append("\n## Crash windows\n")
    L.append("Crash points are drawn uniformly from the first *N* scheduler tasks, where *N* is the median task count of crash-free runs of the same architecture and profile:\n")
    L.append(", ".join(f"{k} {v}" for k, v in data["config"]["crashWindows"].items()) + ".\n")
    (out / "RESULTS.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {out / 'RESULTS.md'}")


if __name__ == "__main__":
    main()
